import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rows = JSON.parse(await readFile(path.join(root, 'data/literature/eukaryotes.snapshot.json'), 'utf8'));
const provenance = JSON.parse(await readFile(path.join(root, 'data/literature/provenance.json'), 'utf8'));
if (!Array.isArray(rows) || rows.length !== provenance.records) throw new Error('Snapshot and provenance counts disagree');
const data = `// Generated by scripts/build-dashboard.mjs; edit the JSON snapshot.\nwindow.HOLI_SNAPSHOT = ${JSON.stringify(rows).replaceAll('<', '\\u003c')};\nwindow.HOLI_PROVENANCE = ${JSON.stringify(provenance)};\n`;
await writeFile(path.join(root, 'dashboard/snapshot.js'), data);
if (process.argv.includes('--standalone')) {
  let html = await readFile(path.join(root, 'index.html'), 'utf8');
  html = html.replace('<link rel="stylesheet" href="dashboard/styles.css">', `<style>${await readFile(path.join(root, 'dashboard/styles.css'), 'utf8')}</style>`);
  for (const file of ['vendor/plotly-2.35.2.min.js', 'snapshot.js', 'data-utils.js', 'app.js']) {
    const source = (await readFile(path.join(root, 'dashboard', file), 'utf8')).replaceAll('</script', '<\\/script');
    html = html.replace(`<script defer src="dashboard/${file}"></script>`, () => `<script>${source}</script>`);
  }
  await mkdir(path.join(root, 'dist'), { recursive: true });
  await writeFile(path.join(root, 'dist/holi-literature.html'), html);
  console.log('Built dist/holi-literature.html (charts and snapshot embedded; gallery links require repository figures).');
}
console.log(`Built dashboard/snapshot.js with ${rows.length} source records.`);
